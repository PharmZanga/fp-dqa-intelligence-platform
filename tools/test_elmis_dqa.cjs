const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {validateDataset,latestVisits,summarize} = require('../assets/elmis-dqa.js');
const record = {id:'test-1',facilityId:'f1',facility:'Facility A',province:'Central',district:'District A',visitDate:'2026-11-02',accessible:'no',utilization:'active',ojtDone:'yes',staffMentored:3,staffCompetent:2,stockouts:['dmpa_sc','iucd'],issues:[{status:'pending',hasOwner:false,deadline:'2026-11-03'}],commodities:[{basisConfirmed:'yes',unit:'vial',cutoff:'2026-11-02T10:00:00+02:00',physicalBefore:0,elmisBefore:0,physicalAfter:10,elmisAfter:10},{basisConfirmed:'yes',unit:'vial',cutoff:'2026-11-02T10:00:00+02:00',physicalBefore:5,elmisBefore:null,physicalAfter:5,elmisAfter:4}]};
validateDataset({schemaVersion:1,round:'round4',records:[record]});
const newer={...record,id:'test-2',visitDate:'2026-11-04',accessible:'yes'};
assert.equal(latestVisits([record,newer]).length,1);
assert.equal(latestVisits([newer,record])[0].id,'test-2');
const m=summarize([record], '2026-11-04');
assert.equal(m.accessible,0);assert.equal(m.utilization.active,1);
assert.equal(m.stockoutFacilities,1);assert.equal(m.stockouts.iucd,1);
assert.equal(m.beforeTotal,1);assert.equal(m.beforeMatch,1);
assert.equal(m.afterTotal,2);assert.equal(m.afterMatch,1);
assert.equal(m.overdue,1);assert.equal(m.missingOwner,1);
assert.equal(m.mentored,3);assert.equal(m.competent,2);
assert.equal(summarize([{...record,stockouts:['not_verified']}]).stockoutKnown,0);
assert.equal(summarize([{...record,stockouts:['none']}]).stockoutKnown,1);
assert.equal(summarize([{...record,staffMentored:null}]).competencyVisits,0);
assert.throws(()=>validateDataset({schemaVersion:1,round:'round4',records:[{...record,stockouts:['none','iucd']}]}));
assert.throws(()=>validateDataset({schemaVersion:1,round:'round4',records:[record,record]}));
const published=validateDataset(JSON.parse(fs.readFileSync(path.join(__dirname,'../data/round4/elmis.json'),'utf8')));
assert.equal(summarize([]).beforeTotal,0);
console.log(`eLMIS indicator tests passed; ${published.records.length} published assessment records validated.`);
